#!/usr/bin/env node
// Regenerates src/generated/{abis,addresses}.ts:
//   1. `forge build --skip test` in ../../contracts (forge from FORGE_BIN, PATH or ~/.foundry/bin)
//   2. `wagmi generate` (ABIs of the six contracts)
//   3. addresses.ts from ../../deployments/<chainId>.json (public networks only; 31337 is local and loaded at runtime)
// `--check` regenerates into memory and fails if the committed files differ (CI sync check).
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const check = process.argv.includes("--check");
const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const contracts = join(root, "../../contracts");
const deployments = join(root, "../../deployments");
const exe = process.platform === "win32" ? ".exe" : "";
const forge =
  process.env.FORGE_BIN ?? (existsSync(join(homedir(), ".foundry/bin", `forge${exe}`)) ? join(homedir(), ".foundry/bin", `forge${exe}`) : "forge");

const before = check ? readGenerated() : null;
execFileSync(forge, ["build", "--skip", "test"], { cwd: contracts, stdio: "inherit" });
execFileSync(process.execPath, [join(root, "node_modules/@wagmi/cli/dist/esm/cli.js"), "generate"], {
  cwd: root,
  stdio: "inherit",
  env: { ...process.env, FORGE_BIN: forge },
});

const KEYS = ["registry", "license", "credits", "reviews", "escrow", "staking"];
const nets = existsSync(deployments)
  ? readdirSync(deployments).filter((f) => /^\d+\.json$/.test(f) && f !== "31337.json").sort()
  : [];
let out = "// Generated by scripts/generate.mjs from deployments/<chainId>.json. Do not edit.\n\n";
out += "export type SolversDeployment = {\n  chainId: number;\n  token: `0x${string}`;\n  treasury: `0x${string}`;\n";
out += KEYS.map((k) => `  ${k}: \`0x\${string}\`;\n`).join("") + "  deployBlock: number;\n  gitSha: string;\n};\n\n";
out += "export const deployments: Readonly<Record<number, SolversDeployment>> = {\n";
for (const f of nets) {
  const d = JSON.parse(readFileSync(join(deployments, f), "utf8"));
  out += `  ${d.chainId}: {\n    chainId: ${d.chainId},\n    token: "${d.token}",\n    treasury: "${d.treasury}",\n`;
  out += KEYS.map((k) => `    ${k}: "${d[k]}",\n`).join("");
  out += `    deployBlock: ${Number(d.deployBlock)},\n    gitSha: "${d.gitSha ?? ""}",\n  },\n`;
}
out += "};\n";
writeFileSync(join(root, "src/generated/addresses.ts"), out);

if (check) {
  const after = readGenerated();
  const stale = Object.keys(after).filter((k) => after[k] !== before[k]);
  if (stale.length) {
    for (const [k, v] of Object.entries(before)) writeFileSync(join(root, "src/generated", k), v);
    console.error(`generated client out of sync: ${stale.join(", ")} (run pnpm --filter @solvers/contracts-client generate)`);
    process.exit(1);
  }
  console.log("generated client in sync");
}

function readGenerated() {
  const dir = join(root, "src/generated");
  return Object.fromEntries(
    ["abis.ts", "addresses.ts"].map((f) => [f, existsSync(join(dir, f)) ? readFileSync(join(dir, f), "utf8") : ""]),
  );
}
